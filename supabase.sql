-- 잔향 위키 건의·질문 창구 (Supabase → SQL Editor에 통째로 붙여 넣고 Run)
-- 여러 번 실행해도 안전합니다. 기존 글은 모두 '공개'로 남습니다.
--
-- 보이는 범위
--   공개 글   : 누구나 읽기
--   비공개 글 : 운영자(Supabase 화면 · service_role)와 남긴 본인(그 브라우저의 열쇠)만
-- 운영자는 Table Editor → ideas 에서 모든 글을 보고 status(new·review·done·hold·answered)와 reply를 고칩니다.

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.ideas (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  cat         text not null default 'idea',
  title       text not null,
  body        text not null,
  nick        text,
  status      text not null default 'new',
  reply       text
);
alter table public.ideas add column if not exists private    boolean not null default false;
alter table public.ideas add column if not exists owner_hash text;   -- 본인 확인용(브라우저 열쇠의 SHA-256). 공개 읽기 대상 아님
create index if not exists ideas_owner_hash_idx on public.ideas (owner_hash);

-- 표 직접 접근: 공개 글의 공개 열만 읽기. 쓰기는 아래 함수로만.
alter table public.ideas enable row level security;
do $$ declare p record; begin
  for p in select policyname from pg_policies where schemaname = 'public' and tablename = 'ideas' loop
    execute format('drop policy %I on public.ideas', p.policyname);
  end loop;
end $$;
create policy ideas_read_public on public.ideas for select to anon, authenticated using (private = false);
revoke all on public.ideas from anon, authenticated;
grant select (id, created_at, cat, title, body, nick, status, reply, private) on public.ideas to anon, authenticated;

-- 글쓰기: 분류는 건의(idea)·질문(ask)만, 열쇠 하나당 하루 5건
create or replace function public.submit_idea(p_cat text, p_title text, p_body text, p_nick text, p_private boolean, p_key text)
returns json language plpgsql security definer set search_path = public, extensions as $$
declare h text; r json;
begin
  if p_cat is null or p_cat not in ('idea', 'ask') then raise exception 'bad category'; end if;
  if char_length(trim(coalesce(p_title, ''))) < 2 or char_length(trim(coalesce(p_body, ''))) < 5 then raise exception 'too short'; end if;
  if p_key is null or p_key !~ '^[0-9a-f]{64}$' then raise exception 'bad key'; end if;
  h := encode(digest(p_key, 'sha256'), 'hex');
  if (select count(*) from public.ideas where owner_hash = h and created_at > now() - interval '1 day') >= 5 then
    raise exception 'daily limit';
  end if;
  insert into public.ideas (cat, title, body, nick, private, owner_hash, status)
  values (p_cat, left(trim(p_title), 60), left(trim(p_body), 1200), nullif(left(trim(coalesce(p_nick, '')), 16), ''),
          coalesce(p_private, false), h, 'new')
  returning json_build_object('id', id) into r;
  return r;
end $$;

-- 내 글(공개·비공개 모두): 열쇠가 맞는 글만 돌려줌
create or replace function public.my_ideas(p_key text)
returns json language plpgsql stable security definer set search_path = public, extensions as $$
begin
  if p_key is null or p_key !~ '^[0-9a-f]{64}$' then return '[]'::json; end if;
  return coalesce((
    select json_agg(json_build_object('id', id, 'created_at', created_at, 'cat', cat, 'title', title, 'body', body,
                                      'nick', nick, 'status', status, 'reply', reply, 'private', private) order by created_at desc)
    from (select * from public.ideas where owner_hash = encode(digest(p_key, 'sha256'), 'hex') order by created_at desc limit 100) t
  ), '[]'::json);
end $$;

revoke all on function public.submit_idea(text, text, text, text, boolean, text) from public;
revoke all on function public.my_ideas(text) from public;
grant execute on function public.submit_idea(text, text, text, text, boolean, text) to anon, authenticated;
grant execute on function public.my_ideas(text) to anon, authenticated;
